function formatPrice(priceCents: number): string {
  return (priceCents / 100).toFixed(2)
}

function makeEdition(
  id: string,
  label: EditionLabel,
  supply: number | null,
  available: number | null,
  priceCents: number,
  maxPerOrder: number,
): NftRecord['editions'][number] {
  return {
    id: `${id}-${editionSlugs[label]}`,
    label,
    supply,
    available,
    price: formatPrice(priceCents),
    maxPerOrder,
    status: available === 0 ? 'sold_out' : 'available',
  }
}

function buildEditions(id: string, mode: EditionMode, priceCents: number): NftRecord['editions'] {
  if (mode === 'emerald') {
    return [
      makeEdition(id, '1/1', 1, 0, 240, 1),
      makeEdition(id, '1/10', 10, 6, 159, 3),
      makeEdition(id, '1/50', 50, 22, 119, 5),
      makeEdition(id, 'Aberta', null, null, 129, 10),
    ]
  }

  if (mode === 'mixed') {
    return [
      makeEdition(id, '1/1', 1, 0, priceCents + 120, 1),
      makeEdition(id, '1/10', 10, 4, priceCents + 40, 3),
      makeEdition(id, '1/50', 50, 12, priceCents, 5),
    ]
  }

  if (mode === 'multi') {
    return [
      makeEdition(id, '1/10', 10, 6, priceCents + 40, 3),
      makeEdition(id, '1/50', 50, 20, priceCents + 20, 5),
      makeEdition(id, 'Aberta', null, null, priceCents, 10),
    ]
  }

  if (mode === 'one') {
    return [makeEdition(id, '1/1', 1, 1, priceCents, 1)]
  }

  if (mode === 'sold') {
    return [makeEdition(id, '1/10', 10, 0, priceCents, 3)]
  }

  return [makeEdition(id, '1/10', 10, 6, priceCents, 3)]
}

function lowestEditionPrice(editions: NftRecord['editions']): string {
  const availableEditions = editions.filter((edition) => edition.status === 'available')
  const candidates = availableEditions.length > 0 ? availableEditions : editions

  return candidates.reduce(
    (lowest, edition) => (compareEth(edition.price, lowest) < 0 ? edition.price : lowest),
    candidates[0]?.price ?? '0.00',
  )
}

function buildReviews(name: string, reviewCount: number, firstReviewNumber: number): NftRecord['reviews'] {
  return Array.from({ length: reviewCount }, (_, reviewIndex) => {
    const reviewNumber = firstReviewNumber + reviewIndex + 1

    return {
      id: `rev-${reviewNumber}`,
      author: reviewAuthors[(reviewNumber - 1) % reviewAuthors.length]!,
      rating: reviewRatings[(reviewNumber - 1) % reviewRatings.length]!,
      comment: reviewComments[(reviewNumber - 1) % reviewComments.length]!.replaceAll('{name}', name),
      createdAt: new Date(Date.UTC(2026, 8, reviewNumber, 12)).toISOString(),
    }
  })
}

function buildNft(entry: SeedEntry, index: number, firstReviewNumber: number): NftRecord {
  const [
    tokenId,
    name,
    art,
    network,
    priceCents,
    editionMode,
    previousPriceCents,
    badge,
    isNew,
    isTrending,
    featured,
    creator,
    royaltiesBps,
    attributes,
    average,
    ratingCount,
    reviewCount,
  ] = entry
  const id = `nft-${String(tokenId).padStart(4, '0')}`
  const collection = categories[index % categories.length]!
  const editions = buildEditions(id, editionMode, priceCents)
  const networkName = networkNames[network]
  const royaltyPercent = royaltiesBps / 100
  const context: StoryContext = {
    name,
    creator,
    network: networkName,
    first: attributes[0].toLowerCase(),
    second: attributes[1].toLowerCase(),
    collection: collection.name,
    royalty: royaltyPercent,
  }
  const story =
    name === 'Emerald Ape #042'
      ? [
          'Emerald Ape #042 é uma obra digital 1/50 finalizada à mão da coleção Kurio Editions. Cada atributo fica armazenado nos metadados do token e verificado na Ethereum. A obra explora identidade, movimento e luz em um mundo digital sem fronteiras.',
          'A propriedade inclui a arte em alta resolução, lançamentos exclusivos para colecionadores e um registro permanente de procedência registrada na rede. Nova Sato recebe 5% de direitos autorais nas vendas secundárias, apoiando novos trabalhos e lançamentos da comunidade.',
        ]
      : [
          storyOpenings[index % storyOpenings.length]!(context),
          storyClosings[index % storyClosings.length]!(context),
        ]
  const description =
    name === 'Emerald Ape #042'
      ? 'Um colecionável digital finalizado à mão da coleção Kurio Editions, verificado na Ethereum, com arte desbloqueável e acesso para colecionadores.'
      : `Uma peça digital da coleção Kurio Editions criada por ${creator}, com procedência registrada na rede ${networkName}.`

  return {
    id,
    name,
    tokenId,
    collection: { id: collection.id, name: collection.name },
    network,
    image: { src: artPaths[art], alt: artAlt[art] },
    price: lowestEditionPrice(editions),
    previousPrice: previousPriceCents === null ? null : formatPrice(previousPriceCents),
    badge,
    availability: editions.every((edition) => edition.status === 'sold_out') ? 'sold_out' : 'available',
    listedAt: new Date(Date.UTC(2026, 9, 15 - index, 12)).toISOString(),
    version: 1,
    description,
    story,
    creator,
    contractAddress: contractAddresses[collection.id],
    royaltiesBps,
    attributes: [...attributes],
    rating: { average, count: ratingCount },
    editions,
    reviews: buildReviews(name, reviewCount, firstReviewNumber),
    isNew,
    isTrending,
    featured,
  }
}

export function buildNftSeed(): NftRecord[] {
  return seedEntries.map((entry, index) => {
    const firstReviewNumber = seedEntries
      .slice(0, index)
      .reduce((total, previousEntry) => total + previousEntry[16], 0)

    return buildNft(entry, index, firstReviewNumber)
  })
}
